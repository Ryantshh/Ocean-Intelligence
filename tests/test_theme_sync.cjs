const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('ai_platform/public/theme-sync.js', 'utf8');
let ready, observers = [], theme = 'dark';
const values = new Map();
const classes = new Set(['light']);
const root = {dataset:{},classList:{contains:x=>classes.has(x),remove:(...xs)=>xs.forEach(x=>classes.delete(x)),add:x=>classes.add(x)},style:{getPropertyValue:x=>values.get(x),setProperty:(x,v)=>values.set(x,v)}};
const parentRoot = {dataset:{theme}};
const document = {readyState:'loading',documentElement:null,addEventListener:(event,fn)=>{ready=fn;}};
const window = {parent:{document:{documentElement:parentRoot}},theme:{dark:{'--background':'dark'},light:{'--background':'light'}},addEventListener:()=>{}};
vm.runInNewContext(source,{window,document,localStorage:{getItem:()=>null,setItem:()=>{}},matchMedia:()=>({matches:false,addEventListener:()=>{}}),MutationObserver:class {constructor(fn){this.fn=fn;} observe(node,opts){assert.ok(node);observers.push({node,opts,fn:this.fn});}}});
assert.equal(observers.length,0,'wait until document exists');
document.documentElement=root; ready();
assert.ok(classes.has('dark')); assert.equal(values.get('--background'),'dark');
values.set('--background','light'); observers[0].fn();
assert.equal(values.get('--background'),'dark','repair React inline variable replacement');
parentRoot.dataset.theme='light'; observers[1].fn();
assert.ok(classes.has('light')); assert.ok(!classes.has('dark')); assert.equal(values.get('--background'),'light');
console.log('Theme sync: early script loading, React updates and dashboard toggle passed.');
